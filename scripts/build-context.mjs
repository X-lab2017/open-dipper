// docs/CONTEXT.json is the only maintained discovery index.
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = path => JSON.parse(readFileSync(resolve(root, path), 'utf8'));
const context = read('docs/CONTEXT.json');
const versions = {
  application: read('package.json').version,
  visual: read('design/tokens.json').version,
};
const machine = {
  ...context,
  versions,
  entries: context.entries.map(entry => ({...entry, url: new URL(entry.path, context.rawBase).href})),
  translations: context.translations.map(group => ({...group, editions: group.editions.map(edition => ({...edition, url: new URL(edition.path, context.rawBase).href}))})),
};
const llms = [
  `# ${context.project}`,
  '',
  `> ${context.description}`,
  '',
  `Repository: ${context.repository}`,
  `Site: ${context.site}`,
  `Application version: ${versions.application}; visual baseline: ${versions.visual}. These do not declare GitHub releases.`,
  '',
  context.notice,
  '',
  '## Language editions',
  '',
  ...machine.translations.map(group => `- ${group.id} (default: ${group.defaultLanguage}): ${group.editions.map(edition => `[${edition.language}](${edition.url})`).join(' | ')}`),
  '',
  '## Authoritative documents',
  '',
  ...machine.entries.map(entry => `- [${entry.title}](${entry.url}): ${entry.purpose}`),
  '',
  '## Machine context',
  '',
  `- [Maintained task index](${context.rawBase}docs/CONTEXT.json)`,
  `- [Published index with document URLs](${context.site}agent-context.json)`,
  '',
  'Generated by npm run docs:build. Edit docs/CONTEXT.json, not this file.',
  '',
].join('\n');
const outputs = new Map([
  ['llms.txt', llms],
  ['public/llms.txt', llms],
  ['public/agent-context.json', JSON.stringify(machine, null, 2) + '\n'],
]);
if (JSON.stringify([...outputs.keys()]) !== JSON.stringify(context.generated)) {
  throw new Error('CONTEXT.json generated list does not match generator outputs');
}
let stale = false;
for (const [path, content] of outputs) {
  const target = resolve(root, path);
  if (process.argv.includes('--check')) {
    let actual;
    try { actual = readFileSync(target, 'utf8'); } catch { /* missing output is stale */ }
    if (actual !== content) { console.error(`Outdated context output: ${path}; run npm run docs:build`); stale = true; }
  } else {
    mkdirSync(dirname(target), {recursive: true});
    writeFileSync(target, content);
  }
}
if (stale) process.exitCode = 1;
else console.log(`Context ${process.argv.includes('--check') ? 'verified' : 'generated'}: ${outputs.size} files`);
