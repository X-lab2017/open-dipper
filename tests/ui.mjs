await page.locator('#search').fill('gitlab-org/modelops');
await page.locator('.source-button').click();
check(await page.locator('.drawer').isVisible(),'mobile evidence drawer opens');
await page.keyboard.press('Escape');
check(errors.length===0,`no runtime page errors (${errors.join(',')})`);
await page.route('**/data/snapshot.json',route=>route.fulfill({status:503,body:'unavailable'}));
