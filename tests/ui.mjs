import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
await mkdir('screenshots', {recursive:true});
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||undefined,headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
const page=await browser.newPage({viewport:{width:1440,height:1050},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
let checks=0;const check=(v,m)=>{assert.ok(v,m);checks++;console.log(`PASS ${m}`)};
await page.goto(process.env.BASE_URL||'http://127.0.0.1:4173/analysis.html');
await page.locator('.stats').waitFor();
check(await page.locator('tbody tr').count()===20,'20 actual sample repositories rendered');
check(await page.locator('.legend-item').count()===3,'initial comparison has three repositories');
check(await page.locator('.chip:not(.selected):disabled').count()===17,'comparison capped at three');
await page.screenshot({path:'screenshots/overview-desktop.png',fullPage:true});
await page.locator('#platform').selectOption('gitlab');
check(await page.locator('tbody tr').count()===1,'GitLab filter restricts table');
check((await page.locator('.legend').innerText()).includes('gitlab-org/modelops/applied-ml/code-suggestions/ai-assist'),'nested GitLab path preserved and comparison reconciled');
await page.locator('#metric').selectOption('stars');
await page.locator('.source-button').first().click();
check((await page.locator('.drawer').innerText()).includes('404'),'not-exported retrieval state shown');
check((await page.locator('.evidence-value strong').innerText())==='—','missing value not zero-filled');
await page.keyboard.press('Escape');check(await page.locator('.drawer').count()===0,'Escape closes drawer');
await page.locator('#platform').selectOption('all');
await page.locator('#metric').selectOption('openrank');
await page.locator('#search').fill('no-match-xyz');
check(await page.locator('tbody tr').count()===0,'empty search state');
await page.locator('#search').fill('');
await page.locator('[data-tab="compare"]').first().click();
await page.locator('#range').selectOption('24');
check(await page.locator('.chart').count()===1,'comparison tab and 24-month range work');
await page.locator('[data-tab="evidence"]').first().click();
check(await page.locator('.definitions article').count()===6,'six metric definitions available');
await page.locator('#language').click();check((await page.locator('h1').innerText()).includes('Every signal'),'English interface switches');
await page.locator('#theme').click();check(await page.locator('html.light').count()===1,'light theme switches');
await page.screenshot({path:'screenshots/evidence-light.png',fullPage:true});
