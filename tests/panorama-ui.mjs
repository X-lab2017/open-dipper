import { chromium, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
await mkdir('screenshots', { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined, headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(process.env.PANORAMA_URL || 'http://127.0.0.1:4173/open-dipper/');
  await expect(page.locator('#earth')).toBeVisible();
  await expect(page.locator('.underbar')).toContainText('非实时');
  await expect.poll(() => page.locator('#earth').evaluate(c => [...c.getContext('2d').getImageData(c.width/2,c.height/2,1,1).data].some(v => v > 0))).toBe(true);
  await page.screenshot({ path: 'screenshots/panorama-desktop.png', fullPage: true });
  await page.locator('#map-mode').click();
  await expect(page.locator('#map-mode')).toHaveClass('active');
  await page.screenshot({ path: 'screenshots/panorama-map-desktop.png', fullPage: true });
  await page.locator('#globe-mode').click();
  await expect(page.locator('#globe-mode')).toHaveClass('active');
  await page.locator('[data-country]').first().click();
  await expect(page.locator('.selected-country h3')).not.toBeEmpty();
  await page.locator('#geo-layer').selectOption('1');
  await expect(page.locator('#geo-layer')).toHaveValue('1');
  await expect(page.locator('.selected-country')).toHaveCount(0);
  for (const id of ['markers', 'grid', 'atmosphere']) {
    await page.locator(`#${id}`).uncheck();
    await expect(page.locator(`#${id}`)).not.toBeChecked();
    await page.locator(`#${id}`).check();
  }
  await page.locator('#zoom-in').click();
  await page.locator('#zoom-out').click();
  await page.locator('#reset').click();
  const geography = await page.locator('.geo-totals').innerText();
  const month = await page.locator('#timeline-month').innerText();
  await page.locator('#play').click();
  await expect(page.locator('#timeline-month')).not.toHaveText(month, { timeout: 10000 });
  await page.locator('#play').click();
  const paused = await page.locator('#timeline-month').innerText();
  await page.waitForTimeout(1600);
  await expect(page.locator('#timeline-month')).toHaveText(paused);
  await expect(page.locator('.geo-totals')).toHaveText(geography, { useInnerText: true });
  await page.locator('#geo-source').click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.locator('#analysis').click();
  await expect(page.frameLocator('iframe').locator('.stats')).toBeVisible();
  await page.locator('.modal-close').click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.locator('#analysis').click();
  await page.locator('.modal-close').click();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect(page.locator('#earth')).toBeVisible();
  await expect(page.locator('.timeline')).toHaveCSS('position', 'relative');
  await page.locator('.focus-panel').scrollIntoViewIfNeeded();
  await expect(page.locator('.focus-panel')).toBeVisible();
  await page.locator('#repo-source').click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.locator('.modal-close').click();
  await page.screenshot({ path: 'screenshots/panorama-mobile-cards.png' });
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: 'screenshots/panorama-mobile.png', fullPage: true });
  await page.locator('#about').click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.locator('.modal-close').click();
  expect(errors).toEqual([]);
  console.log('Panorama desktop/mobile browser smoke passed');
} finally { await browser.close(); }
